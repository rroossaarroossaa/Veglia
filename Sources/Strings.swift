        case tipOn            // icon tooltip: watching
        case tipOff           // icon tooltip: resting
        case language         // "Language" item
        case systemLanguage   // "Same as system" in the language submenu
        case lidMode          // "Work with the lid closed"
        case lidWarnTitle     // warning title
        case lidWarnText      // warning text: heat, battery, password
        case enable           // "Turn on" button
        case cancel           // "Cancel" button
        case lidFailed        // helper install failed
        case watchAgents      // "Watch agents"
        case agentsHint       // hint inside the agents submenu
        case terminals        // "While a terminal is open"
        case terminalName     // "Terminal" in the status line
