    /// Language picked in the menu; nil means same as system. Stored in UserDefaults.
    static var override: String? {
        get { let v = UserDefaults.standard.string(forKey: "language"); return (v ?? "").isEmpty ? nil : v }
        set { UserDefaults.standard.set(newValue ?? "", forKey: "language") }
    }

    static func t(_ key: Key) -> String {
        tables[lang]?[key] ?? tables["en"]![key]!
    }

    /// Current language: the picked one, otherwise the system one.
    static var lang: String { override.flatMap { tables[$0] != nil ? $0 : nil } ?? systemLang }

    /// System language code mapped to a table key (zh-Hans and zh-Hant are distinguished).
    static let systemLang: String = {
        let pref = Locale.preferredLanguages.first ?? "en"
        if pref.hasPrefix("zh") {
            return (pref.contains("Hant") || pref.contains("TW") || pref.contains("HK")) ? "zh-Hant" : "zh-Hans"
        }
        let code = String(pref.split(separator: "-").first ?? "en")
        return tables[code] != nil ? code : "en"
    }()

